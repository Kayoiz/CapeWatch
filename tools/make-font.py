# Builds assets/fonts/CapeWatchPixel.ttf: CapeWatch's own pixel font for cape names and numbers.
# Every glyph is drawn here by hand on a 5-wide grid. Rows 0-6 sit on the baseline (row 6 is the bottom
# row); rows 7-8 are descenders. Letters that are easy to confuse are drawn apart on purpose:
#   C/c are open on the right (O/o are closed), 0 has a slash (O has none), 1 has a flag and a foot,
#   I has bars top and bottom, l has a tail, 5 has a flat top (S is rounded), 2 has a curved top (Z is flat),
#   8 is round on the left (B is flat), g has a closed top (y is open), f hooks up and t hooks down.
# Also Russian (Cyrillic) and the accented letters of Spanish, Portuguese, French and German, so text in those
# languages never switches to another font in the middle of a word. Hebrew is shown in the normal font.
# Run: python tools/make-font.py
