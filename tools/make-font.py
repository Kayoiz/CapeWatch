# Same drawing as an existing letter: Cyrillic letters that look like Latin ones (ё/Ё = ë/Ë), and the no-break spaces.
ALIAS = {'А': 'A', 'В': 'B', 'Е': 'E', 'К': 'K', 'М': 'M', 'Н': 'H', 'О': 'O', 'Р': 'P', 'С': 'C', 'Т': 'T', 'Х': 'X',
         'а': 'a', 'е': 'e', 'о': 'o', 'р': 'p', 'с': 'c', 'у': 'y', 'х': 'x', 'ё': 'ë', 'Ё': 'Ë',
         ' ': ' ', ' ': ' '}   # no-break spaces (French numbers and dates)

def width(rows):
    return max((len(r) for r in rows), default=0)

def draw(rows, y0=0):
    pen = TTGlyphPen(None)
    for y, row in enumerate(rows, start=y0):
        x = 0
        while x < len(row):
            if row[x] != '#': x += 1; continue
            x0 = x
            while x < len(row) and row[x] == '#': x += 1
            top = (ASC - y) * PX; bot = top - PX
            # clockwise outer contour (TrueType)
            pen.moveTo((x0 * PX, bot)); pen.lineTo((x0 * PX, top)); pen.lineTo((x * PX, top)); pen.lineTo((x * PX, bot)); pen.closePath()
    return pen.glyph()

names = {ch: ('space' if ch == ' ' else 'uni%04X' % ord(ch)) for ch in G}
order = ['.notdef'] + [names[c] for c in G]
glyphs = {'.notdef': draw(["####", "#..#", "#..#", "#..#", "#..#", "#..#", "####"])}
metrics = {'.notdef': (5 * PX, 0)}
for ch, rows in G.items():
    glyphs[names[ch]] = draw(rows, -1 if ch in TALL else 0)
    metrics[names[ch]] = ((width(rows) + 1) * PX, 0)

fb = FontBuilder(1000, isTTF=True)
fb.setupGlyphOrder(order)
fb.setupCharacterMap({**{ord(c): names[c] for c in G}, **{ord(c): names[base] for c, base in ALIAS.items()}})
fb.setupGlyf(glyphs)
fb.setupHorizontalMetrics(metrics)
fb.setupHorizontalHeader(ascent=(ASC + 1) * PX, descent=-DESC * PX)
fb.setupNameTable({'familyName': 'CapeWatch Pixel', 'styleName': 'Regular', 'copyright': '(c) Kayoiz. All rights reserved.'})
fb.setupOS2(sTypoAscender=(ASC + 1) * PX, sTypoDescender=-DESC * PX, sTypoLineGap=0, usWinAscent=(ASC + 1) * PX, usWinDescent=DESC * PX, fsType=0)
fb.setupPost()
out = Path(__file__).resolve().parent.parent / 'assets' / 'fonts' / 'CapeWatchPixel.ttf'
out.parent.mkdir(parents=True, exist_ok=True)
fb.save(str(out))

# Self-check: no two glyphs may share the same pixels (catches a letter drawn like another one).
seen = {}
for ch, rows in G.items():
    key = tuple(r.rstrip('.') for r in rows)
    if key in seen and {ch, seen[key]} != {"'", '’'}:
        raise SystemExit(f'glyphs {seen[key]!r} and {ch!r} are identical')
    seen[key] = ch
print('wrote', out, len(G), 'glyphs')
